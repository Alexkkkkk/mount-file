"""Smoke the shared bounded read-only VFS contract across native providers.

Each case supplies its own filesystem image. The runner disables the legacy
pytsk3 fallback and validates listing, stat, full reads, bounded range reads,
and safe extraction. Reports include opaque image hashes and explicitly do not
claim independent-oracle parity unless a separate checker is run.
"""

from __future__ import annotations

import hashlib
import tempfile
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from mountfile import vfs
from mountfile.extract import extract_file

_READ_OPERATIONS = ("list", "stat", "read-file", "read-range", "extract")
_READ_ONLY_FALLBACK_REASON = (
    "synthetic/prebuilt fixture assertions validate native behavior only; "
    "an independent oracle was not run by this matrix"
)


@dataclass(frozen=True)
class ParityCase:
    """One bounded filesystem image and its expected regular-file contents."""

    fs_name: str
    image_path: Path
    expected_files: Mapping[str, bytes]
    offset: int = 0
    volume_size: int | None = None
    profile_id: str | None = None
    fixture_kind: str = "synthetic"
    fixture_source: str = "generated by a test fixture builder"
    source_fixture_sha256: str | None = None
    expected_image_sha256: str | None = None


@dataclass
class ParityReport:
    """Aggregate result and content-addressed evidence for a read matrix."""

    ran: list[str] = field(default_factory=list)
    failures: dict[str, str] = field(default_factory=dict)
    checks: int = 0
    cases: list[dict[str, object]] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.failures and bool(self.ran)


def _normalized_file_path(path: str) -> PurePosixPath:
    if (
        not isinstance(path, str)
        or not path.startswith("/")
        or "\x00" in path
        or "\\" in path
        or any(part in ("", ".", "..") for part in path.split("/")[1:])
    ):
        raise ValueError(f"expected a normalized absolute VFS file path: {path!r}")
    normalized = PurePosixPath(path)
    if normalized.as_posix() != path:
        raise ValueError(f"expected a normalized absolute VFS file path: {path!r}")
    return normalized


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while True:
            chunk = stream.read(1024 * 1024)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def _new_case_evidence(case: ParityCase) -> dict[str, object]:
    return {
        "case": case.fs_name,
        "profile_id": case.profile_id or case.fs_name,
        "fixture": {
            "kind": case.fixture_kind,
            "source": case.fixture_source,
            "source_sha256": case.source_fixture_sha256,
            "size_bytes": None,
            "sha256": None,
            "sha256_after": None,
            "source_unchanged": None,
        },
        "backend": None,
        "operations": {operation: "not_claimed" for operation in _READ_OPERATIONS},
        "native_status": "pending",
        "independent_oracle": {
            "status": "not_claimed",
            "reason": _READ_ONLY_FALLBACK_REASON,
        },
        "checks": 0,
    }


def _run_case(case: ParityCase, evidence: dict[str, object]) -> int:
    image = Path(case.image_path).expanduser().resolve()
    if not image.is_file():
        raise ValueError(f"image is not a regular file: {image.name}")
    image_size = image.stat().st_size
    fixture = evidence["fixture"]
    fixture["size_bytes"] = image_size
    fixture["sha256"] = _sha256_file(image)
    if (
        case.expected_image_sha256 is not None
        and fixture["sha256"] != case.expected_image_sha256
    ):
        raise ValueError("fixture SHA-256 does not match its pinned manifest")

    offset = case.offset
    volume_size = case.volume_size
    if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0:
        raise ValueError("filesystem offset must be a non-negative integer")
    if volume_size is None:
        volume_size = image_size - offset
    if (
        isinstance(volume_size, bool)
        or not isinstance(volume_size, int)
        or volume_size <= 0
        or offset + volume_size > image_size
    ):
        raise ValueError("filesystem extent is invalid or exceeds the image")
    if not case.expected_files:
        raise ValueError("parity case must contain at least one expected file")

    provider = vfs.open_image_provider(
        image,
        offset=offset,
        volume_size=volume_size,
        allow_legacy_fallback=False,
    )
    evidence["backend"] = str(
        getattr(provider, "backend_name", type(provider).__name__)
    )
    checks = 0
    try:
        backend_name = str(getattr(provider, "backend_name", ""))
        if not backend_name.startswith("native-"):
            raise AssertionError(
                f"expected a native backend, got {backend_name or type(provider).__name__}"
            )

        normalized_files = [
            (file_path, _normalized_file_path(file_path), expected)
            for file_path, expected in case.expected_files.items()
        ]
        listed_by_parent: dict[str, set[str]] = {}
        with tempfile.TemporaryDirectory(prefix="mountfile-native-parity-") as tmp:
            extraction_root = Path(tmp)
            for operation in _READ_OPERATIONS:
                evidence["current_operation"] = operation
                for index, (file_path, normalized, expected) in enumerate(
                    normalized_files
                ):
                    if not isinstance(expected, bytes):
                        raise TypeError(
                            f"expected contents for {file_path!r} must be bytes"
                        )
                    if operation == "list":
                        parent = normalized.parent.as_posix()
                        if parent not in listed_by_parent:
                            entries = provider.list_dir(parent)
                            listed_by_parent[parent] = {
                                str(entry.get("name", "")).casefold()
                                for entry in entries
                            }
                        if normalized.name.casefold() not in listed_by_parent[parent]:
                            raise AssertionError(
                                f"list_dir({parent!r}) did not contain {normalized.name!r}"
                            )
                    elif operation == "stat":
                        metadata = provider.stat(file_path)
                        if metadata.get("is_dir") or int(
                            metadata.get("size", -1)
                        ) != len(expected):
                            raise AssertionError(
                                f"stat({file_path!r}) returned unexpected type/size: {metadata!r}"
                            )
                    elif operation == "read-file":
                        if provider.read_file(file_path) != expected:
                            raise AssertionError(
                                f"read_file({file_path!r}) content differs"
                            )
                    elif operation == "read-range":
                        range_offset = min(1, len(expected))
                        range_length = min(17, len(expected) - range_offset)
                        ranged = provider.read_file_range(
                            file_path, range_offset, range_length
                        )
                        if (
                            ranged
                            != expected[range_offset : range_offset + range_length]
                        ):
                            raise AssertionError(
                                f"read_file_range({file_path!r}) content differs"
                            )
                    elif operation == "extract":
                        destination = extraction_root / f"file-{index:04d}.bin"
                        written = extract_file(provider, file_path, destination)
                        if (
                            written != len(expected)
                            or destination.read_bytes() != expected
                        ):
                            raise AssertionError(
                                f"extract_file({file_path!r}) content differs"
                            )
                    checks += 1
                evidence["operations"][operation] = "pass"
        evidence.pop("current_operation", None)
    except Exception:
        operation = evidence.pop("current_operation", None)
        if operation in evidence["operations"]:
            evidence["operations"][operation] = "failed"
        raise
    finally:
        close = getattr(provider, "close", None)
        if callable(close):
            close()
    return checks


def run_parity_matrix(cases: Iterable[ParityCase]) -> ParityReport:
    """Run the common read-only contract against each supplied native image.

    A failed case is recorded while later cases continue. The report is
    successful only when at least one case ran and every case passed.
    """
    report = ParityReport()
    seen: set[str] = set()
    materialized = list(cases)
    if not materialized:
        raise ValueError("parity matrix must contain at least one case")

    for case in materialized:
        if (
            not isinstance(case, ParityCase)
            or not isinstance(case.fs_name, str)
            or not case.fs_name.strip()
            or case.fs_name in seen
        ):
            raise ValueError("parity case names must be non-empty and unique")
        seen.add(case.fs_name)

    for case in materialized:
        evidence = _new_case_evidence(case)
        report.cases.append(evidence)
        image = Path(case.image_path).expanduser().resolve()
        try:
            report.checks += _run_case(case, evidence)
            fixture = evidence["fixture"]
            fixture["sha256_after"] = _sha256_file(image)
            fixture["source_unchanged"] = fixture["sha256_after"] == fixture["sha256"]
            if not fixture["source_unchanged"]:
                raise AssertionError("source image changed during read-only parity run")
        except Exception as exc:
            evidence["native_status"] = "failed"
            report.failures[case.fs_name] = f"{type(exc).__name__}: {exc}"
            evidence["failure"] = report.failures[case.fs_name]
            try:
                if image.is_file():
                    fixture = evidence["fixture"]
                    fixture["sha256_after"] = _sha256_file(image)
                    fixture["source_unchanged"] = (
                        fixture["sha256_after"] == fixture["sha256"]
                    )
            except OSError:
                pass
        else:
            evidence["native_status"] = "pass"
            evidence["checks"] = sum(len(case.expected_files) for _ in _READ_OPERATIONS)
            report.ran.append(case.fs_name)
    return report


__all__ = ["ParityCase", "ParityReport", "run_parity_matrix"]
